/* ============================================================
   THE LET GO LIST'S PHRASES, FOUND IN WHAT A PERSON WRITES. 21 November.

   The owner, on the list he dictated and wrote in September: "the 96
   patterns, the 17,000 lines, let's get that in too." Two jobs were named
   for it. This file is the first: short phrase cues, so the engine can see
   when what someone types or says is a line of the list. The second, the
   packs a person can open and save, is ui/letgopacks.js and the Wisdom
   school. Both are generated by tools/regen-letgo.cjs from Reboot-OS's
   atuned/data/letgo and canon_tables, read as git blobs at a named commit,
   and engine/data/letgo.js carries that commit and every blob.

   WHAT A CUE IS. A phrase from the list: either a tail of the dictation,
   the thing after "I'm letting go of" (Reboot-OS's letgo_tails.py), or a
   title of two words or more from the list's own index. Each carries the
   seat Reboot-OS filed it under. For a tail that seat is the seat of the
   fetter its topic was joined to by Reboot-OS's word join; for an index title
   it is the seat the index files it under, with the channel and layer the
   index gives. Either way it is a fact about the list, not about a person.

   WHAT A MATCH MAY BE USED FOR, AND WHAT IT MAY NOT. letgoCues(text) says
   which of the list's phrases occur in the text, where, and under which
   seat the list files each one. It is carried on sniffStory's contract as
   `letgo` so a reader of the reading can see it beside the evidence. It is
   not charge: nothing here feeds parseStory, applyStory, compute() or any
   score, and nothing here places an imprint, because adding weight to a
   seat for a phrase match would change every reading that carries one, and
   that is a ruling on the reading, not part of a port. It is not negation
   aware: "I am not afraid of change" contains "afraid of change", and the
   match says so plainly rather than pretending to a reading of the clause.

   HOW IT MATCHES. The text goes through normMap, the sniffer's own
   normalisation, and each cue is looked for between word boundaries. Cues
   are tried longest first and a span already claimed is not claimed twice,
   so "giving up on myself" is one hit and not also "giving up". The raw
   offsets come back through normMap's own map, so a renderer can mark the
   person's own characters.

   THE ENGINE MAY NOT TOUCH THE HOST and this file does not. It loads after
   engine/export.js, because export.js assigns module.exports whole and a
   name added before it is wiped (the first cut sat beside sniff.js and
   exported nothing). It reads sniff.js's normMap and K2B at call time.
   ============================================================ */
var LETGO_ROW=null;
/* the snapshot's rows as objects, built once on the first call */
function letgoRows(){
 if(LETGO_ROW)return LETGO_ROW;
 LETGO_ROW=LETGO_SNAPSHOT.cues.map(function(r){
  var o={cue:r[0], seats:r[1].split(' ').map(function(k){return K2B[k];}), from:r[2]==='i'?'index':'tail', said:r[3]};
  if(r[2]==='i'){o.n=r[4]; o.channel=r[5]||null; o.layer=r[6]||null;}
  return o;});
 return LETGO_ROW;}
function letgoCount(){return letgoRows().length;}
/* every phrase of the list in the text, in the order they occur, and how
   many land under each seat. A copy each call, so a caller that edits an
   answer cannot change the next one. */
function letgoCues(text){
 var t=String(text||''), nm=normMap(t), s=nm.s, claimed=[], hits=[], seats={};
 if(s.length<3)return {hits:[], seats:{}};
 letgoRows().forEach(function(r){
  var k=' '+r.cue+' ', at=s.indexOf(k);
  while(at>=0){
   var lo=at+1, hi=at+1+r.cue.length, free=true;
   for(var i=0;i<claimed.length;i++)if(lo<claimed[i][1]&&hi>claimed[i][0]){free=false;break;}
   if(free){
    claimed.push([lo,hi]);
    var h={cue:r.cue, said:r.said, seats:r.seats.slice(), from:r.from,
     at:nm.map[lo], end:nm.map[hi-1]+1};
    if(r.from==='index'){h.n=r.n; h.channel=r.channel; h.layer=r.layer;}
    hits.push(h);}
   at=s.indexOf(k,at+1);}});
 hits.sort(function(a,b){return a.at-b.at;});
 hits.forEach(function(h){h.seats.forEach(function(b){seats[b]=(seats[b]||0)+1;});});
 return {hits:hits, seats:seats};}

if(typeof module!=='undefined'&&module.exports){
 Object.assign(module.exports,{letgoCues:letgoCues, letgoCount:letgoCount, LETGO_SNAPSHOT:LETGO_SNAPSHOT});}
